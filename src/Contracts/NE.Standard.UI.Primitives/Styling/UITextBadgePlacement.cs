namespace NE.Standard.UI.Primitives.Styling;

/// <summary>
/// Defines where badge in text content is placed.
/// </summary>
public enum UITextBadgePlacement
{
    /// <summary>
    /// The badge is placed inline within the text content.
    /// </summary>
    Inline = 0,

    /// <summary>
    /// The badge is placed after the text content.
    /// </summary>
    Trailing = 1,
}
