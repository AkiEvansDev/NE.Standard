namespace NE.Standard.UI.Primitives.Styling;

/// <summary>
/// Defines the edge of its parent a component is attached to — the side a panel folds toward when it
/// collapses.
/// </summary>
public enum UISide
{
    /// <summary>
    /// The left edge.
    /// </summary>
    Left = 0,

    /// <summary>
    /// The right edge.
    /// </summary>
    Right = 1,

    /// <summary>
    /// The top edge.
    /// </summary>
    Top = 2,

    /// <summary>
    /// The bottom edge.
    /// </summary>
    Bottom = 3,
}
