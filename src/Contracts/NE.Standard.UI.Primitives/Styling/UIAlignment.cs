namespace NE.Standard.UI.Primitives.Styling;

/// <summary>
/// Defines cross-axis or main-axis alignment for UI layout.
/// </summary>
public enum UIAlignment
{
    /// <summary>
    /// Aligns content to the start of the axis.
    /// </summary>
    Start = 0,

    /// <summary>
    /// Aligns content to the center of the axis.
    /// </summary>
    Center = 1,

    /// <summary>
    /// Aligns content to the end of the axis.
    /// </summary>
    End = 2,

    /// <summary>
    /// Stretches content to fill the axis.
    /// </summary>
    Stretch = 3,
}
