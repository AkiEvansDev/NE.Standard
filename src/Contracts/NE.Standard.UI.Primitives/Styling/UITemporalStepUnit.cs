namespace NE.Standard.UI.Primitives.Styling;

/// <summary>
/// Defines time units used by temporal input step values.
/// </summary>
public enum UITemporalStepUnit
{
    /// <summary>
    /// The step value is expressed in days.
    /// </summary>
    Day = 0,

    /// <summary>
    /// The step value is expressed in hours.
    /// </summary>
    Hour = 1,

    /// <summary>
    /// The step value is expressed in minutes.
    /// </summary>
    Minute = 2,

    /// <summary>
    /// The step value is expressed in seconds.
    /// </summary>
    Second = 3,
}
