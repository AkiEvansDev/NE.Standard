namespace NE.Standard.UI.Primitives.Styling;

/// <summary>
/// Defines semantic text roles used by text components.
/// </summary>
public enum UITextType
{
    /// <summary>
    /// The largest, most prominent typographic role, for hero-style text.
    /// </summary>
    Display = 0,

    /// <summary>
    /// The typographic role for primary headings.
    /// </summary>
    Title = 1,

    /// <summary>
    /// The typographic role for secondary headings.
    /// </summary>
    Subtitle = 2,

    /// <summary>
    /// The typographic role for regular body text.
    /// </summary>
    Body = 3,

    /// <summary>
    /// The typographic role for small, supplementary text.
    /// </summary>
    Caption = 4,

    /// <summary>
    /// The typographic role for small label text placed above content.
    /// </summary>
    Overline = 5,
}
