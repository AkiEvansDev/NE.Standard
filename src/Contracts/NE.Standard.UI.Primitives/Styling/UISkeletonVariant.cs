namespace NE.Standard.UI.Primitives.Styling;

/// <summary>
/// Defines skeleton placeholder presentation variants.
/// </summary>
public enum UISkeletonVariant
{
    /// <summary>
    /// Placeholder shaped like a line of text.
    /// </summary>
    Text = 0,

    /// <summary>
    /// Placeholder shaped like a rectangular card.
    /// </summary>
    Card = 1,

    /// <summary>
    /// Placeholder shaped like a circle (e.g. an avatar).
    /// </summary>
    Circle = 2,
}
