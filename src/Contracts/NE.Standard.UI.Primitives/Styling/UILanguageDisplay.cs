namespace NE.Standard.UI.Primitives.Styling;

/// <summary>
/// What a language switcher's button shows for the language the page is in.
/// </summary>
public enum UILanguageDisplay
{
    /// <summary>
    /// The language's code, upper-cased (<c>EN</c>, <c>ZH-HANS</c>).
    /// </summary>
    Code = 0,

    /// <summary>
    /// The language's own name for itself (<c>English</c>, <c>Русский</c>).
    /// </summary>
    Name = 1
}
