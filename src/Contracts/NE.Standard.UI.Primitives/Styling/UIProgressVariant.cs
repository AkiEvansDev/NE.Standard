namespace NE.Standard.UI.Primitives.Styling;

/// <summary>
/// Defines progress indicator presentation variants.
/// </summary>
public enum UIProgressVariant
{
    /// <summary>
    /// Renders progress as a horizontal bar.
    /// </summary>
    Linear = 0,

    /// <summary>
    /// Renders progress as a circular ring.
    /// </summary>
    Circular = 1,
}
