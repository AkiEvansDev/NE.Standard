namespace NE.Standard.UI.Primitives.Items;

/// <summary>
/// Defines the sort direction for an items view.
/// </summary>
public enum UIItemsSortDirection
{
    /// <summary>
    /// Sorts items from lowest to highest.
    /// </summary>
    Ascending = 0,

    /// <summary>
    /// Sorts items from highest to lowest.
    /// </summary>
    Descending = 1
}
